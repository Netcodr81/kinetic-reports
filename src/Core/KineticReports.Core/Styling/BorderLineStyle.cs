namespace KineticReports.Core.Styling;

/// <summary>Specifies the line style used when drawing a border side.</summary>
public enum BorderLineStyle
{
    /// <summary>No border line is drawn.</summary>
    None,

    /// <summary>A solid continuous line.</summary>
    Solid,

    /// <summary>A dashed line.</summary>
    Dashed,

    /// <summary>A dotted line.</summary>
    Dotted,

    /// <summary>Alternating dashes and dots.</summary>
    DashDot,
}
