namespace KineticReports.Core.Styling;

/// <summary>Specifies horizontal text alignment within a layout element.</summary>
public enum TextAlignment
{
    /// <summary>Text is aligned to the left edge.</summary>
    Left,

    /// <summary>Text is centered horizontally.</summary>
    Center,

    /// <summary>Text is aligned to the right edge.</summary>
    Right,

    /// <summary>Text is stretched to fill the full available width (justified).</summary>
    Justify,
}
