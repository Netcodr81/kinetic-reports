namespace KineticReports.Core.Styling;

/// <summary>
/// Specifies the weight (stroke thickness) of a font face.
/// Values follow the CSS font-weight numeric scale.
/// </summary>
public enum FontWeight
{
    /// <summary>Thin weight (100).</summary>
    Thin = 100,

    /// <summary>Extra-light weight (200).</summary>
    ExtraLight = 200,

    /// <summary>Light weight (300).</summary>
    Light = 300,

    /// <summary>Normal / regular weight (400).</summary>
    Normal = 400,

    /// <summary>Medium weight (500).</summary>
    Medium = 500,

    /// <summary>Semi-bold weight (600).</summary>
    SemiBold = 600,

    /// <summary>Bold weight (700).</summary>
    Bold = 700,

    /// <summary>Extra-bold weight (800).</summary>
    ExtraBold = 800,

    /// <summary>Black / heavy weight (900).</summary>
    Black = 900,
}
